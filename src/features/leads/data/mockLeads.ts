const NOW = Date.now();

function hoursAgo(hours: number): string {
  return new Date(NOW - hours * 60 * 60 * 1000).toISOString();
}

function hoursAhead(hours: number): string {
  return new Date(NOW + hours * 60 * 60 * 1000).toISOString();
}

let historySequence = 0;

function history(
  event: string,
  description: string,
  occurredAt: string,
  actorName = "Sistema Brasilab",
  actorId = "SYS",
  origin: LeadHistoryEntry["origin"] = "sistema",
): LeadHistoryEntry {
  historySequence += 1;
  return {
    id: `LHT-${String(historySequence).padStart(4, "0")}`,
    event,
    description,
    occurredAt,
    actorId,
    actorName,
    origin,
  };
}

let scheduleSequence = 0;

function schedule(input: {
  leadId: string;
  title: string;
  description: string;
  scheduledFor: string;
  status: LeadSchedule["status"];
  isFirstContact: boolean;
  ownerId: string;
  ownerName: string;
  createdAt: string;
}): LeadSchedule {
  scheduleSequence += 1;
  return { id: `LSC-${String(scheduleSequence).padStart(4, "0")}`, ...input };
}

